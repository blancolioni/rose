#!/usr/bin/env python3
"""Write the Ada glyph table of an 8x16 BDF font, for Rose.Drawing.Text.

Reads a BDF font whose bounding box is 8 by 16 pixels, such as Spleen's
spleen-8x16.bdf (https://github.com/fcambus/spleen), and writes the spec of
Rose.Drawing.Text.Font to standard output: a glyph for each Latin-1
character, as 16 rows of 8 pixels, bit 7 the leftmost.  A character the
font has no glyph for, such as a control character, has an empty glyph.

Usage: bdf-to-ada.py FONT.bdf > rose-drawing-text-font.ads

The font's COMMENT lines, which carry its copyright and licence, are copied
into the spec's header.
"""

import sys


def main():
    if len(sys.argv) != 2:
        print("usage: bdf-to-ada.py FONT.bdf", file=sys.stderr)
        return 2

    comments = []
    glyphs = {}
    box = None
    encoding = None
    bbx = None
    bitmap = None

    for line in open(sys.argv[1], encoding="latin-1"):
        words = line.split()
        if not words:
            continue
        key = words[0]
        if key == "COMMENT":
            comments.append(line[len("COMMENT"):].strip())
        elif key == "FONTBOUNDINGBOX":
            box = tuple(int(w) for w in words[1:5])
        elif key == "ENCODING":
            encoding = int(words[1])
        elif key == "BBX":
            bbx = tuple(int(w) for w in words[1:5])
        elif key == "BITMAP":
            bitmap = []
        elif key == "ENDCHAR":
            if encoding is not None and 0 <= encoding < 256:
                glyphs[encoding] = place(box, bbx, bitmap)
            encoding = bbx = bitmap = None
        elif bitmap is not None:
            bitmap.append(int(key, 16))

    if box is None or box[0] != 8 or box[1] != 16:
        print("bdf-to-ada.py: the font is not 8 by 16", file=sys.stderr)
        return 1

    write(comments, glyphs)
    return 0


def place(box, bbx, bitmap):
    """The glyph's 16 rows, from its bitmap placed in the font's box."""
    width, height, x_offset, y_offset = bbx
    ascent = box[1] + box[3]
    top = ascent - (height + y_offset)
    rows = [0] * 16
    bytes_per_row = (width + 7) // 8
    for i, value in enumerate(bitmap):
        row = top + i
        if 0 <= row < 16:
            # Left-justify the row in 8 bits, then shift by the x offset.
            value >>= 8 * bytes_per_row - 8
            rows[row] = (value >> (x_offset - box[2])) & 0xFF
    return rows


def write(comments, glyphs):
    out = sys.stdout
    out.write("--  Generated by scripts/bdf-to-ada.py: do not edit.  The glyphs"
              " are from\n--  this font:\n--\n")
    for comment in comments:
        out.write(("--  " + comment).rstrip() + "\n")
    out.write("--\n--  The font's LICENSE file is beside this one, with the "
              "font's name\n--  before it: SPLEEN-LICENSE for Spleen.\n")
    out.write("""
package Rose.Drawing.Text.Font is

   pragma Preelaborate;

   --  A glyph for each Latin-1 character: 16 rows of 8 pixels, top first,
   --  with bit 7 of a row its leftmost pixel.

   type Glyph_Row is mod 2 ** 8;
   type Glyph is array (0 .. 15) of Glyph_Row;

   Glyphs : constant array (Character) of Glyph :=
""")
    entries = []
    for code in range(256):
        rows = glyphs.get(code, [0] * 16)
        if not any(rows):
            continue
        entries.append("Character'Val (%d) =>\n          (%s)"
                       % (code, wrap(rows)))
    out.write("       (" + ",\n        ".join(entries))
    out.write(",\n        others => (others => 0));\n\n"
              "end Rose.Drawing.Text.Font;\n")


def wrap(rows):
    """The 16 rows, eight to a line."""
    cells = ["16#%02X#" % r for r in rows]
    return ", ".join(cells[:8]) + ",\n           " + ", ".join(cells[8:])


if __name__ == "__main__":
    sys.exit(main())
